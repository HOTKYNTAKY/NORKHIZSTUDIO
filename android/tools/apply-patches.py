#!/usr/bin/env python3
"""Append NEON TIDE's mobile tuning layer to the minified web bundle.

The game has no separate source tree here — only the built
`assets/index-<hash>.js`. Rather than hand-edit minified code, this script:

  * concatenates everything in android/patches/ into assets/__nt-patches.js
    (wrapped in one IIFE, so several patch files can share a scope), and
  * appends to the end of the bundle, after its own boot() call:

        window.__neonTideEngine = <engine>;        // the live engine object
        window.__neonTideBundleReady(<engine>);    // runs the patches

    `<engine>` is read from the bundle's own boot statements, so the patches
    receive the real engine (console, flow, player, atmosphere, ...).

Usage: apply-patches.py <assets-dir>
"""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PATCH_DIR = os.path.join(os.path.dirname(HERE), "patches")
IMPORT_MARK = "/* neon-tide mobile patches */"

# The bundle ends with e.g.  var $9=new Sge(Q9);...$9.boot();
# Find the engine instantiation by pairing "var X = new Y(...)" with "X.boot()".
BOOT_RE = re.compile(
    r"var\s+([A-Za-z_$][\w$]*)\s*=\s*new\s+([A-Za-z_$][\w$]*)\s*\(\s*[A-Za-z_$][\w$]*\s*\)"
)

APPEND = """{mark}
window.__neonTideEngine = {engine};
try {{ window.__neonTideBundleReady({engine}); }} catch (e) {{ console.warn('[neon-tide] patch boot failed', e); }}
"""

HEADER = """/*
 * NEON TIDE — mobile tuning layer (generated by android/tools/apply-patches.py)
 * Sources: android/patches/*.js — edit those, not this file.
 */
(function () {
'use strict';
"""


def patch_names() -> list[str]:
    names = [n for n in sorted(os.listdir(PATCH_DIR)) if n.endswith(".js")]
    if not names:
        raise SystemExit(f"no patch files in {PATCH_DIR}")
    return names


def main() -> int:
    if len(sys.argv) != 2:
        print("usage: apply-patches.py <assets-dir>", file=sys.stderr)
        return 2
    assets = sys.argv[1]

    bundles = [n for n in os.listdir(assets) if re.fullmatch(r"index-[A-Za-z0-9_-]+\.js", n)]
    if len(bundles) != 1:
        print(f"expected exactly one index-*.js bundle, found {bundles}", file=sys.stderr)
        return 1
    bundle = os.path.join(assets, bundles[0])
    code = open(bundle, encoding="utf-8").read()
    if IMPORT_MARK in code:
        print("    bundle already patched, skipping")
        return 0

    candidates = [m for m in BOOT_RE.finditer(code) if f"{m.group(1)}.boot()" in code[m.end():]]
    if len(candidates) != 1:
        print(
            "expected exactly one engine instantiation followed by .boot(), found "
            f"{[m.group(1) for m in candidates]}; refusing to patch",
            file=sys.stderr,
        )
        return 1
    engine = candidates[0].group(1)

    names = patch_names()
    parts = [HEADER]
    for name in names:
        body = open(os.path.join(PATCH_DIR, name), encoding="utf-8").read().rstrip()
        parts.append(f"/* ---------------- {name} ---------------- */\n{body}\n\n")
    parts.append("})();\n")
    open(os.path.join(assets, "__nt-patches.js"), "w", encoding="utf-8").write("".join(parts))

    with open(bundle, "a", encoding="utf-8") as fh:
        fh.write("\n" + APPEND.format(mark=IMPORT_MARK, engine=engine))

    print(f"    patched {bundles[0]} (engine {engine}); patches: {', '.join(names)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
