<?php
declare(strict_types=1);

require_once __DIR__ . '/../../config/app.php';
require_once __DIR__ . '/../../config/database.php';
require_once __DIR__ . '/../../middleware/auth.php';

use Norkhiz\Config\App;
use Norkhiz\Config\Database;

header('Content-Type: application/json; charset=utf-8');

$user = requireAuth($_SERVER, $_COOKIE);
$pdo  = Database::connect();

// multipart upload
if (!isset($_FILES['video']) || $_FILES['video']['error'] !== UPLOAD_ERR_OK) {
    http_response_code(400);
    echo json_encode(['error' => 'video_file_required'], JSON_UNESCAPED_UNICODE);
    exit;
}

$file = $_FILES['video'];
$maxMb = (int)(App::env('MAX_UPLOAD_MB', 2048));
if ($file['size'] > $maxMb * 1024 * 1024) {
    http_response_code(413);
    echo json_encode(['error' => 'file_too_large'], JSON_UNESCAPED_UNICODE);
    exit;
}

$allowedMime = ['video/mp4', 'video/mpeg', 'video/quicktime', 'video/x-matroska', 'video/webm'];
$finfo = new finfo(FILEINFO_MIME_TYPE);
$mime = $finfo->file($file['tmp_name']);
if (!in_array($mime, $allowedMime, true)) {
    http_response_code(415);
    echo json_encode(['error' => 'unsupported_mime'], JSON_UNESCAPED_UNICODE);
    exit;
}

$storage = App::env('STORAGE_PATH', __DIR__ . '/../storage');
$videosDir = $storage . '/videos';
$hlsDir = $storage . '/hls';
@mkdir($videosDir, 0750, true);
@mkdir($hlsDir, 0750, true);

$slug = preg_replace('/[^\p{L}\p{N}-]+/u', '-', trim($_POST['title'] ?? ''));
$slug = mb_substr(trim($slug, '-'), 0, 120);
if ($slug === '') $slug = 'video-' . uniqid();
$slug .= '-' . bin2hex(random_bytes(4));

$dest = $videosDir . '/' . $slug . '.' . pathinfo($file['name'], PATHINFO_EXTENSION);
if (!move_uploaded_file($file['tmp_name'], $dest)) {
    http_response_code(500);
    echo json_encode(['error' => 'upload_failed'], JSON_UNESCAPED_UNICODE);
    exit;
}

$title = trim($_POST['title'] ?? 'بدون عنوان');
$desc = trim($_POST['description'] ?? '');
$categoryId = $_POST['category_id'] ?? null;
$isPremium = filter_var($_POST['is_premium'] ?? '0', FILTER_VALIDATE_BOOLEAN);

// hls manifest path (placeholder — in production generated by ffmpeg job)
$hlsManifest = "hls/{$slug}/index.m3u8";

$pdo->prepare("INSERT INTO videos (user_id, category_id, title, slug, description, hls_manifest, is_premium, quality_max, poster)
               VALUES (?, ?, ?, ?, ?, ?, ?, '1080', NULL)")
    ->execute([$user['id'], $categoryId ?: null, $title, $slug, $desc, $hlsManifest, $isPremium ? 1 : 0]);

echo json_encode([
    'ok' => true,
    'video' => ['id' => (int)$pdo->lastInsertId(), 'slug' => $slug, 'title' => $title],
    'message' => 'فایل بارگذاری شد. در صف پردازش HLS قرار گرفت.',
], JSON_UNESCAPED_UNICODE);